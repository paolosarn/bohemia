# THE FEED'S POSTS, PART ONE: WHAT YOU DID AND WHAT THE WORLD DID (WORDS, 10/26/26, rule 215).
# Every line is draft:true (the build stamps it). A variant is V(en, es, *tags):
#   en   the post in plain English (no Spanish word in it: the dial adds the Spanish, never a coin flip here)
#   es   its Spanglish twin, the same post as a Spanglish speaker types it, or None (then the dial's flavour())
#   tags 'saw' = the poster saw it; 'heard' = it reached them second hand (Q15 spec 3: a post sounds its
#        distance); 'ah' = the analog horror is in what they noticed (for EYES' read, not a gate's claim)
# Q15's rules hold every line: it names a person or talks to one; 'somebody' is never the one who did it;
# a deed is a report from a mouth (a place, a detail, who says it), never the ledger read aloud.

def V(en, es=None, *tags):
    return {'en': en, 'es': es, 'tags': list(tags)}

def kind(id, k, who, fills, teaches, trigger, words, big=False, every=None, after=None):
    return {'id': id, 'kind': k, 'who': who, 'fills': fills, 'teaches': teaches, 'big': big,
            'suggest': {'trigger': trigger, 'every_min': every, 'after_min': after,
                        'note': 'FEED owns the trigger and the pacing; these are WORDS\' suggestions'},
            'words': words}

