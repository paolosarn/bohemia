ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ALPHA = os.path.join(ROOT, 'slices/BOHEMIA_ALPHA_0_9.html')
ANCHOR = 'function synthV(kind,AC,MAST,hz,sd,semi,t,g0){\n'


def _graveyard_names():
    try:
        txt = open(os.path.join(ROOT, 'gates', 'bohemia_graveyard.txt'), encoding='utf8').read()
    except Exception:
        return set()
    return set(re.findall(r"^n:'([^']+)'\s*\|", txt, re.M))


VOICES = r"""  /* ===== BATCH 25 VOICES (8/26/26) — four topologies this rack has never had.
     His order: "we need more voices and different instruments sounds and shit."
     Chosen by searching the 582 that exist for the TECHNIQUE rather than the
     name, and every near miss is ruled out in tools/bohemia_music_batch25.py.
     SCREECH LAW: nothing here delays, convolves or feeds back. Three of the
     four are computed into a buffer sample by sample, which is how they can be
     real physics with no delay line in the graph. */
  if(kind==='scanstring'){
    /* SCANNED SYNTHESIS (Verplank, Shaw & Mathews, Interval Research 1998-99).
       A ring of 64 masses joined by springs is STRUCK at note-on, then
       integrated at a slow rate while the whole ring is read out as one cycle
       at the pitch. THE WAVETABLE IS COMPUTED BY PHYSICS -- not authored, not
       crossfaded between presets -- and it keeps changing for the length of the
       note as the string settles.
       NOT granular (grains are independent; these masses are coupled). NOT
       modal (modes are fixed and summed; this spectrum evolves). NOT wavemorph,
       which crossfades two WaveShapers. */
    const M=64, CYC=128, dur=Math.max(0.35, sd*4);
    const cycles=Math.max(8, Math.ceil(dur*hz(semi)/1));
    const bf=AC.createBuffer(1, cycles*CYC, AC.sampleRate), d=bf.getChannelData(0);
    const x=new Float32Array(M), v=new Float32Array(M);
    for(let i=0;i<M;i++) x[i]=Math.sin(2*Math.PI*i/M)*0.6;
    x[8]+=0.9;                                  /* the strike */
    const K=0.28, CENTRE=0.004, DAMP=0.0022;
    let w=0;
    for(let c=0;c<cycles;c++){
      for(let s=0;s<CYC;s++){
        const p=s*M/CYC, i0=Math.floor(p), fr=p-i0;
        d[w++]=x[i0%M]*(1-fr)+x[(i0+1)%M]*fr;
      }
      for(let i=0;i<M;i++){
        const a=(x[(i-1+M)%M]+x[(i+1)%M]-2*x[i])*K - x[i]*CENTRE - v[i]*DAMP;
        v[i]+=a;
      }
      for(let i=0;i<M;i++) x[i]+=v[i];
    }
    let pk=0; for(let i=0;i<d.length;i++) pk=Math.max(pk,Math.abs(d[i]));
    if(pk>0) for(let i=0;i<d.length;i++) d[i]/=pk;
    const src=AC.createBufferSource(), g=AC.createGain(), lp=AC.createBiquadFilter();
    src.buffer=bf; src.loop=false;
    /* one CYC-sample cycle must last exactly one period of the note */
    src.playbackRate.value = hz(semi)*CYC/AC.sampleRate;
    lp.type='lowpass'; lp.frequency.value=Math.min(9000, hz(semi)*11); lp.Q.value=0.6;
    g.gain.setValueAtTime(0.0001,t);
    g.gain.linearRampToValueAtTime(g0*0.9,t+0.02);
    g.gain.exponentialRampToValueAtTime(0.0001,t+sd*3.6);
    src.connect(lp); lp.connect(g); g.connect(MAST);
    src.start(t); src.stop(t+sd*3.8); return;
  }
  if(kind==='syncthorn'){
    /* HARD SYNC, and this rack has never had oscillator sync at all. The slave
       saw is FORCE-RESET to zero every time the master period wraps; the slave's
       own pitch is swept across the note, so the discontinuity marches through
       the waveform and the timbre climbs while the PITCH DOES NOT MOVE.
       NOT detune: fatsaw, saw3v, detune and unisonsplit are stacks of
       free-running saws a few cents apart and none of them resets anything,
       which is the entire mechanism here. */
    const dur=Math.max(0.3, sd*3.2), N=Math.floor(AC.sampleRate*dur);
    const bf=AC.createBuffer(1,N,AC.sampleRate), d=bf.getChannelData(0);
    const f0=hz(semi), SR=AC.sampleRate;
    let mp=0, sp=0;
    for(let i=0;i<N;i++){
      const u=i/N, sw=1-Math.abs(2*u-1), ratio=1.0+8.5*sw*sw;   /* UP AND BACK:
         a sync sweep that only climbs reads as a bright lead, which is why the
         one-way version measured next to `saw3`. Rising and returning is the
         shape nothing else in this rack makes. */          /* the sync sweep, and WIDE: 1x to 8.5x
         on a square law, which is the whole character of hard sync. At 1.5-4.9x
         linear it measured closer to `resonlead` than a typical pair of existing
         voices are to each other -- a timid sync is just a bright lead. */
      mp+=f0/SR; if(mp>=1){ mp-=1; sp=0; }     /* THE reset. this is hard sync */
      sp+=f0*ratio/SR; if(sp>=1) sp-=1;
      d[i]=(2*sp-1)*0.5;
    }
    const src=AC.createBufferSource(), g=AC.createGain(), lp=AC.createBiquadFilter();
    src.buffer=bf;
    lp.type='lowpass'; lp.frequency.value=Math.min(11000, f0*16); lp.Q.value=0.9;
    g.gain.setValueAtTime(0.0001,t);
    g.gain.linearRampToValueAtTime(g0,t+0.012);
    g.gain.exponentialRampToValueAtTime(0.0001,t+sd*3);
    src.connect(lp); lp.connect(g); g.connect(MAST);
    src.start(t); src.stop(t+dur); return;
  }
  if(kind==='pafvox'){
    /* PHASE-ALIGNED FORMANT (Miller Puckette, 1995). The carrier is RE-PHASED at
       the start of every fundamental period and windowed by a raised cosine
       raised to a power, so the formant can glide continuously with no
       discontinuity and no filter.
       NOT formantvox (a saw through bandpass filters -- subtractive). NOT
       atriumvox (FOF: a sum of independently decaying grains). PAF is ONE
       continuous carrier whose phase is disciplined by the fundamental. */
    const dur=Math.max(0.3, sd*3.4), N=Math.floor(AC.sampleRate*dur);
    const bf=AC.createBuffer(1,N,AC.sampleRate), d=bf.getChannelData(0);
    const f0=hz(semi), SR=AC.sampleRate;
    let p=0;
    for(let i=0;i<N;i++){
      const u=i/N, fc=f0*(1.6+9.4*u) + f0*0.5;  /* the formant glides, FAR, and the
         +f0*0.5 parks it BETWEEN harmonics -- an inharmonic formant is the thing
         PAF can do that a talkbox physically cannot. At 2.6-7x and harmonically
         aligned it measured closer to `talkbox` than a typical existing pair. */
      p+=f0/SR; if(p>=1) p-=1;
      const bw=1.6+9.0*(1-u);   /* AND THE BANDWIDTH MOVES AGAINST THE CENTRE, which
         is the thing PAF has and a filter sweep does not: the formant starts
         wide and low and ends narrow and high, two independent motions from one
         carrier. Locked together they measured next to `hoover`. */
      const wdw=Math.pow(0.5*(1+Math.cos(2*Math.PI*(p-0.5))), bw);
      d[i]=wdw*Math.cos(2*Math.PI*fc*(p/f0))*0.62;
    }
    const src=AC.createBufferSource(), g=AC.createGain(), hp=AC.createBiquadFilter();
    src.buffer=bf;
    hp.type='highpass'; hp.frequency.value=Math.max(60, f0*0.5); hp.Q.value=0.5;
    g.gain.setValueAtTime(0.0001,t);
    g.gain.linearRampToValueAtTime(g0*0.95,t+0.03);
    g.gain.exponentialRampToValueAtTime(0.0001,t+sd*3.2);
    src.connect(hp); hp.connect(g); g.connect(MAST);
    src.start(t); src.stop(t+dur); return;
  }
  if(kind==='bowdrag'){
    /* STICK-SLIP FRICTION -- the Helmholtz motion of a bowed string. A friction
       curve whose grip falls off hyperbolically with relative velocity drives a
       resonator, and THE OSCILLATION IS NOT MADE BY AN OSCILLATOR: it emerges
       because the bow grabs the string, drags it, and loses it, hundreds of
       times a second. The first voice in this rack whose pitch is a consequence
       rather than a setting.
       NOT musicsaw / wineglass / glassharp / ebow. All four of those are a sine
       with an LFO on it, which is what a bowed note SOUNDS like from across a
       room and is not what a bow DOES.
       THE NORMAL FORCE SCALES WITH PITCH, and that is not a tuning nicety: at a
       fixed press it self-oscillated up to 440 Hz and went silent above it
       (crossing ratio 0.15 at 660), because a stiffer string needs a harder
       press to be dragged as far. Measured across 55-1200 Hz it now tracks at
       0.89-0.98 of the ideal rate, and the shortfall is correct -- Helmholtz
       motion is a sawtooth with a fast flyback, not a sine. */
    const dur=Math.max(0.3, sd*3.4), N=Math.floor(AC.sampleRate*dur);
    const bf=AC.createBuffer(1,N,AC.sampleRate), d=bf.getChannelData(0);
    const SR=AC.sampleRate, f0=hz(semi), w=2*Math.PI*f0;
    const K=w*w, C=w*0.08, VB=0.28, FN=w*VB*1.2, dt=1/SR;
    let x=0, vv=0, blew=false;
    for(let i=0;i<N;i++){
      const vbow=VB*Math.min(1, i/(SR*0.04));
      const vrel=vbow-vv;
      const mu=1/(1+Math.abs(vrel)*40);
      const F=mu*(vrel>=0?1:-1)*FN;
      vv+=(F-K*x-C*vv)*dt; x+=vv*dt;
      if(!isFinite(x)){ blew=true; break; }
      d[i]=x;
    }
    if(blew){ for(let i=0;i<N;i++) d[i]=0; }
    let pk=0; for(let i=0;i<N;i++) pk=Math.max(pk,Math.abs(d[i]));
    if(pk>0) for(let i=0;i<N;i++) d[i]/=pk;
    const src=AC.createBufferSource(), g=AC.createGain(), lp=AC.createBiquadFilter();
    src.buffer=bf;
    lp.type='lowpass'; lp.frequency.value=Math.min(7000, f0*9); lp.Q.value=0.7;
    g.gain.setValueAtTime(0.0001,t);
    g.gain.linearRampToValueAtTime(g0*0.85,t+0.05);   /* a bow does not click in */
    g.gain.exponentialRampToValueAtTime(0.0001,t+sd*3.2);
    src.connect(lp); lp.connect(g); g.connect(MAST);
    src.start(t); src.stop(t+dur); return;
  }
"""

