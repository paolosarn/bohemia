NEW = ['scanstring', 'syncthorn', 'pafvox', 'bowdrag']
NEW_SONGS = ['THE STRING THAT KEEPS MOVING', 'A NOTE THAT CLIMBS WITHOUT RISING',
             'SOMETHING IN THE PIPE IS SHAPING WORDS', 'THE BOW WILL NOT LET GO']


def main():
    write = '--write' in sys.argv
    s = open(ALPHA, encoding='utf8').read()
    changed = []

    # EVERY VOICE AND DRUM THIS BATCH NAMES MUST HAVE A BODY. Caught the hard
    # way: this batch shipped a hat called 'shaker', which drumV has never had,
    # so that song's hat would have been silently nothing. music_gate found it,
    # but a batch tool that can invent an instrument name should refuse itself
    # before a gate has to -- the tool knows what it is about to write.
    # RESOLVED THE WAY THE GAME RESOLVES IT, not the way I assumed. The first
    # cut looked only for `kind==='x'` and flagged `clickh`, which is a real
    # hat -- drumV keeps its hats as UNQUOTED TABLE KEYS, so a kind-only search
    # sees a working instrument as a ghost. music_gate already had the correct
    # rule and this now uses it: a body is a synthV kind, a quoted drum name, or
    # a drum table key.
    _kinds = set(re.findall(r"kind==='([a-z_0-9]+)'", s))
    _keys = set(re.findall(r"\b([a-z][a-z0-9]*)\s*:\s*[\[{]", s))
    _bodies = _kinds | _keys
    _named = set(re.findall(r"(?:\bb|\bl|\bam|\bk|\bh):'([a-z_0-9]+)'", SONGS))
    _ghosts = sorted(n for n in _named if n not in _bodies and n not in NEW)
    if _ghosts:
        print('FAIL: this batch names instrument(s) with no body in synthV/drumV: %s'
              % ', '.join(_ghosts))
        return 1

    have = [v for v in NEW if ("kind==='%s'" % v) in s]
    if not have:
        if ANCHOR not in s:
            print('FAIL: synthV signature moved; refusing to guess where a voice goes')
            return 1
        # SCREECH LAW, checked on what is about to go in rather than after
        for bad in ('createDelay', 'createConvolver'):
            if bad in VOICES:
                print('FAIL: SCREECH LAW -- this batch contains %s' % bad)
                return 1
        s = s.replace(ANCHOR, ANCHOR + VOICES, 1)
        changed.append('4 voices born: ' + ', '.join(NEW))
    else:
        print('  voices already installed: %s' % ', '.join(have))

    dead = _graveyard_names()
    refused = [n for n in NEW_SONGS if n in dead]
    if refused:
        print('REFUSING: graveyard is final and these are dead: %s' % ', '.join(refused))
        return 1

    if NEW_SONGS[0] not in s:
        i = s.index('const MLOOPS=')
        st = s.index('[', i)
        d = 0
        end = -1
        for k in range(st, len(s)):
            if s[k] == '[':
                d += 1
            elif s[k] == ']':
                d -= 1
                if not d:
                    end = k
                    break
        if end < 0:
            print('FAIL: could not find the end of MLOOPS')
            return 1
        # THE CLOSING `\n];` IS AN ANCHOR THE SONG LOCK MEASURES FROM. Batch 24
        # learned this the expensive way: splicing before the `]` removed the
        # newline and the lock's span ran on to the next `\n];` in the file,
        # measuring MLOOPS at 991,094 bytes instead of 31,446.
        tail = s[end - 1:end + 2]
        if tail != '\n];':
            print('FAIL: MLOOPS does not close with a newline + ]; -- refusing to guess')
            return 1
        s = s[:end - 1] + ',\n' + SONGS + '\n];' + s[end + 2:]
        changed.append('4 songs: ' + ', '.join(NEW_SONGS))

    # NEW_VIBES IS "THE CURRENT FRESH COOK", BY ITS OWN COMMENT, and it was
    # still listing seven songs from batch 24 -- three of which Paolo KILLED on
    # 8/26. It drives the NEW badge in the MUSIC tab AND it is the list
    # voice_audible_gate walks, so a stale one means the badge lies to him and
    # the newest voices are the only ones nobody is checking. Pointed at this
    # batch, which is what it is for.
    m = re.search(r"(NEW_VIBES\s*=\s*\[)(.*?)(\])", s, re.S)
    if not m:
        print('FAIL: NEW_VIBES not found; the NEW badge and the voice gate both read it')
        return 1
    want = ','.join("'%s'" % n for n in NEW_SONGS)
    if m.group(2).strip() != want:
        s = s[:m.start(2)] + want + s[m.end(2):]
        changed.append('NEW_VIBES points at this batch (was %d stale name(s), '
                       '3 of them buried)' % len(re.findall(r"'", m.group(2))) )

    print('=== MUSIC BATCH 25 ===')
    if not changed:
        print('  already applied (idempotent, nothing to do)')
        return 0
    for c in changed:
        print('  ' + c)
    if not write:
        print('\n(--write to install)')
        return 0
    open(ALPHA, 'w', encoding='utf8').write(s)
    print('  wrote %s' % os.path.relpath(ALPHA, ROOT))
    print('  NEXT: node gates/song_lock_gate.js --write  (MLOOPS changed on purpose)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
