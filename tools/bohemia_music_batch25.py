"""
BOHEMIA — MUSIC BATCH 25 (8/26/26). FOUR TOPOLOGIES THIS RACK HAS NEVER HAD.

HIS ORDER, on his 8/26 verdict export, verbatim:

    "we need more voices and different instruments sounds and shit. so yeah
     keep cooking"

A STANDING ORDER, not a one-off. This is the first batch answering it.

REUSE CHECK: cooks new VOICES, which is the thing asked for, so the check is the
one that matters here -- NOT "did I open a bank" but "does this rack already do
this". It reads all 582 melodic voices in synthV and rules out the near misses by
name. Nothing here is a recolour of something already in there, and where a
technique LOOKS like one that exists, the reason it is not is written down.

THE VARIETY LAW IS ABOUT TOPOLOGY, NOT COUNT. 582 voices built four ways are
582 cousins. So the question was never "what instrument is missing" -- it was
"what PHYSICS is missing", and the rack was searched for the technique, not the
name.

WHAT IS ALREADY IN THERE (measured, by grepping synthV's own comments):
    FM 32 · waveshaping 23 · comb 24 · pluck 22 · formant 14 · additive 9
    PWM 9 · ring mod 6 · chant 6 · modal 5 · Shepard 4 · granular 3
    bitcrush 3 · talkbox 2 · Karplus 1 · FOF 1 · phase distortion 1 · vocoder 1

WHAT WAS NOT, AND IS NOW:

  1. scanstring — SCANNED SYNTHESIS (Verplank, Shaw and Mathews, Interval
     Research, 1998-99). A ring of 64 masses joined by springs is STRUCK at
     note-on and then integrated at a slow "haptic" rate while the whole ring is
     read out as one cycle at the pitch. The wavetable is not authored and not
     interpolated between presets -- IT IS COMPUTED BY PHYSICS, and it keeps
     evolving for the length of the note as the string settles.
     NOT granular (grains are independent; these masses are coupled to their
     neighbours). NOT modal (modes are fixed and summed; this is a finite
     element model whose spectrum changes as it decays). NOT wavemorph, which
     crossfades two WAVESHAPERS. Nothing in the rack computes a wave.

  2. syncthorn — HARD SYNC, and the rack has never had oscillator sync at all
     (the word appears zero times in 582 voices). A slave saw is FORCE-RESET to
     zero every time the master period wraps, and the slave's pitch is swept
     across the note, so the discontinuity marches through the waveform and the
     timbre screams upward without the pitch moving.
     NOT detune. fatsaw, saw3v, detune and unisonsplit are all stacks of
     free-running saws a few cents apart; none of them resets anything, which is
     the entire mechanism here. That is also why SUPERSAW WAS RULED OUT of this
     batch: it is exactly those four wearing a fifth name.

  3. pafvox — PHASE-ALIGNED FORMANT (Miller Puckette, 1995). A carrier is
     re-phased at the start of EVERY fundamental period and windowed by a
     raised cosine raised to a power, so a formant bump can glide continuously
     with no discontinuity and no filter.
     NOT formantvox, which is a saw through a bank of bandpass filters -- a
     SUBTRACTIVE formant. NOT atriumvox, which is FOF: a sum of independently
     decaying grains. PAF is one continuous carrier whose phase is disciplined
     by the fundamental. Three different ways to make a vowel; the rack had two.

  4. bowdrag — STICK-SLIP FRICTION, the Helmholtz motion of a bowed string.
     A friction curve (grip falls off hyperbolically with relative velocity)
     drives a resonator, and the oscillation is NOT generated by an oscillator
     at all: it emerges because the bow grabs the string, drags it, and loses
     it, hundreds of times a second.
     NOT musicsaw, wineglass, glassharp or ebow. All four of those are a sine
     oscillator with an LFO on it, which is what a bowed note SOUNDS like from
     a distance and is not what a bow DOES. This is the first voice in the rack
     whose pitch is a consequence rather than a setting.

MEASURED BEFORE ANY OF IT WAS WRITTEN INTO THE ALPHA, offline in node:
     scanstring  peak 1.32  rms 0.281  zc 2046   (normalised on the way in)
     syncthorn   peak 0.50  rms 0.287  zc 1446
     pafvox      peak 0.60  rms 0.211  zc 2530
     bowdrag     FAILED FIRST: zc 4. It was creeping, not slipping -- the string
                 velocity had been scaled by 0.002, so the relative velocity
                 never changed sign and the "friction" was a constant DC push.
                 With the bow and the string in the same units it self-oscillates
                 at pitch. THEN IT FAILED AGAIN above 440 Hz (ratio 0.15 at
                 660): a stiffer resonator needs a harder press, so the normal
                 force scales with frequency. Across 55-1200 Hz it now tracks
                 at 0.89-0.98 of the ideal crossing rate -- the shortfall is
                 correct, because Helmholtz motion is a sawtooth with a fast
                 flyback rather than a sine.

SCREECH LAW: no createDelay, no createConvolver, no feedback path anywhere.
Three of the four are computed into an AudioBuffer sample by sample, which is
how they can be real physics without a delay line in the graph.

  python3 tools/bohemia_music_batch25.py           # report
  python3 tools/bohemia_music_batch25.py --write   # install
"""
