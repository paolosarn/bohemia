/* ============================================================================
   INTRODUCTIONS GATE (8/12/26, PEOPLE lane) — THE SIXTEEN ARE REAL, AND THEY
   REACH THE PLAYER.

   Law: laws/BOHEMIA_ADDENDUM_THE_SIXTEEN_INTRODUCTIONS_8_12_26.md
   Organ: engine/bohemia_introductions.js (generated by tools/bohemia_introductions.py)

   WHAT THIS IS DEFENDING, and it is not hypothetical. Every faction dossier
   Paolo thumbed UP on 8/2/26 carries a WHEN YOU ASK THEIR NAME section, and every
   one of them is a different MECHANIC. They sat in records/factions/ for ten days
   and the only two files in the repo that had ever opened them were the generator
   that wrote them and the gate that checks they exist. Meanwhile the game did the
   same thing for all sixteen: one button, one full name, everybody.

   So the failure modes this gate is built against, in order of how likely they
   are to actually happen:

     1. THE SHAPE DRIFTS OFF THE WORDS. The mechanic is a READING of his canon.
        Somebody rewords a dossier, the reading is now wrong, and nothing notices.
        -> the generator is RE-RUN here and its output diffed byte-for-byte, so a
           reworded dossier fails this gate rather than shipping a stale shape.

     2. IT IS WIRED BY NAME AND DEAD IN FACT. This lane has already been burned
        exactly once (8/9: advance_territory was "wired", a name-grep said so, and
        it had never fired since the day it shipped). A grep for
        `bohemia_introductions` in the run proves NOTHING.
        -> part C opens the REAL built run in a REAL browser and reads what the
           player's own card resolves to, per person, through the run's own
           reporting hook. Behaviour or it did not happen.

     3. THE CARD SAYS TWO THINGS. bohemia_people.js hands over the full name the
        moment the ledger says you asked. If the organ says you only got a
        SURNAME and the NAME row still prints the whole thing, the card contains
        its own contradiction -- the exact bug class this lane shipped on 8/11
        (two numbers, both right, one card).
        -> part C asserts the built run rewrites the row from the organ, and part
           B asserts the organ never hands back more than the rule allows.

     4. WORDS GET INVENTED. MECHANISM-MINE / CONTENTS-PAOLO'S. The organ is
        allowed to arrange his canon; it is not allowed to write dialogue or cook
        a name pool.
        -> part D sweeps the generated module for a dialogue table and for
           quoted speech, and asserts every label it can return is derived from
           something the engine already owned.

     5. THE UNAFFILIATED REGRESS. ~85% of the valley runs with nobody, and their
        introduction is Paolo's 7/31 ruling (YOU HAVE TO ASK) which is already
        shipped and already loved. A faction layer that changes THAT is a
        regression wearing a feature's clothes.
        -> part B pins the DEFAULT rule to exactly the old behaviour.

   node gates/introductions_gate.js
   ============================================================================ */
