let pass = 0, fail = 0;
function ok(claim, cond, detail) {
  if (cond) { pass++; console.log('  ok  ' + claim); }
  else { fail++; console.log('  FAIL ' + claim + (detail ? '\n       ' + detail : '')); }
}
function requirePlaywright() {
  const globals = ['/opt/node22/lib/node_modules', '/usr/lib/node_modules', '/usr/local/lib/node_modules'];
  for (const g of globals) { try { return require(path.join(g, 'playwright')); } catch (_e) {} }
  return require('playwright');
}

const I = require(ORGAN);
const CTX = { full: 'RUBEN HOLLAND', trade: 'SCAVENGER', work: 'NORTH ROAD RUN' };
const ALL = { asked: true, hires: 2, vouched: true, standing: true, honest: true,
              overheard: true, introduced: true };

/* ---------------------------------------------------------------- A. CANON */
function partA() {
  console.log('A. THE RULES ARE HIS, AND THEY HAVE NOT DRIFTED OFF THE WORDS');

  const files = fs.readdirSync(DOSSIERS)
    .filter(f => /^BOHEMIA_FACTION_.*\.md$/.test(f))
    .map(f => f.replace(/^BOHEMIA_FACTION_/, '').replace(/\.md$/, ''));
  const keys = I.keys();

  ok('A1 every faction dossier on disk has an introduction rule',
    files.every(f => keys.includes(f)),
    'missing: ' + files.filter(f => !keys.includes(f)).join(', '));
  ok('A2 no rule exists for a faction with no dossier',
    keys.every(k => files.includes(k)),
    'orphans: ' + keys.filter(k => !files.includes(k)).join(', '));
  ok('A3 there are sixteen of them', keys.length === 16, 'got ' + keys.length);

  /* THE ANCHOR. Each rule declares a verbatim fragment of the dossier sentence it
     was read out of. This is what makes the mechanic a CLAIM ABOUT HIS CANON that
     a machine can check, instead of a private interpretation. */
  let anchored = 0, canonMatched = 0;
  keys.forEach(k => {
    const r = I.RULES[k];
    const doc = fs.readFileSync(path.join(DOSSIERS, 'BOHEMIA_FACTION_' + k + '.md'), 'utf8');
    const flat = doc.replace(/\s+/g, ' ');
    if (r.anchor && flat.includes(r.anchor)) anchored++;
    if (r.canon && flat.includes(r.canon.slice(0, 120))) canonMatched++;
  });
  ok('A4 every rule\'s anchor sentence is verbatim in its own dossier',
    anchored === keys.length, anchored + '/' + keys.length);
  ok('A5 every rule carries its dossier paragraph verbatim, not a paraphrase',
    canonMatched === keys.length, canonMatched + '/' + keys.length);

  /* THE GENERATOR IS THE ONLY AUTHOR. Re-run it and diff. A hand-edit to the
     baked module, or a reworded dossier, both die here. */
  const before = fs.readFileSync(ORGAN, 'utf8');
  let regen = null;
  try { execFileSync('python3', [TOOL], { cwd: ROOT, stdio: 'pipe' }); regen = fs.readFileSync(ORGAN, 'utf8'); }
  catch (e) { regen = 'GENERATOR REFUSED TO RUN: ' + (e.stderr || e.message); }
  ok('A6 the baked organ is exactly what the generator produces right now',
    regen === before,
    regen && regen.startsWith('GENERATOR REFUSED') ? regen.slice(0, 300)
      : 'engine/bohemia_introductions.js was hand-edited, or a dossier changed under it');
}

/* ------------------------------------------------------------ B. MECHANICS */
function partB() {
  console.log('B. SIXTEEN MECHANICS, NOT SIXTEEN LABELS');

  const keys = I.keys();

  /* DISTINCTNESS, MEASURED. The whole claim of this feature is that meeting a
     Trades member is not the same act as meeting a Mob member. If the sixteen
     collapse onto three behaviours the feature is decoration. Signature = what
     the player actually observes across the meeting: what they hold at first
     contact, after pressing the button, and after every earning condition is
     satisfied, plus whether there is a button at all. */
  const sig = k => {
    const r = I.RULES[k];
    return JSON.stringify([
      I.meeting(r, CTX, {}).shown, I.meeting(r, CTX, { asked: true }).shown,
      I.meeting(r, CTX, ALL).shown, I.buttonFor(r, CTX, {}),
      I.meeting(r, CTX, {}).asks, I.askOutcome(r, CTX, {}).cost]);
  };
  const sigs = keys.map(sig);
  const distinct = new Set(sigs).size;
  ok('B1 at least 13 of the sixteen are behaviourally distinct from each other',
    distinct >= 13, 'distinct signatures: ' + distinct + '/16');

  /* the collisions that remain must be HIS: two factions his canon describes the
     same way are allowed to behave the same way. Name them so a future session
     sees them rather than rediscovering them. */
  const byS = {};
  keys.forEach((k, i) => { (byS[sigs[i]] = byS[sigs[i]] || []).push(k); });
  Object.values(byS).filter(g => g.length > 1)
    .forEach(g => console.log('       (canon twins, allowed: ' + g.join(' = ') + ')'));

  /* THE NAMED-IN-CANON ONES, one claim each, driven not read. These are the
     sentences that say the word "mechanic" out loud in his dossiers. */
  const T = I.RULES.TRADES;
  ok('B2 TRADES: asking gets a trade, and only TWO HIRES gets the name',
    I.meeting(T, CTX, { asked: true }).shown === 'SCAVENGER' &&
    !I.meeting(T, CTX, { asked: true, hires: 1 }).isName &&
    I.meeting(T, CTX, { asked: true, hires: 2 }).shown === CTX.full);

  const M = I.RULES.MOB;
  ok('B3 MOB: asking gets nothing and costs you; a vouch gets the name',
    I.askOutcome(M, CTX, {}).got === 'nothing' &&
    /PERMANENT MARK/.test(I.askOutcome(M, CTX, {}).cost) &&
    I.meeting(M, CTX, { vouched: true }).shown === CTX.full);

  const C = I.RULES.CARTEL;
  ok('B4 CARTEL: the mechanic runs backwards - they used yours, you never get theirs',
    I.meeting(C, CTX, {}).used === true &&
    I.meeting(C, CTX, ALL).shown === null &&
    I.meeting(C, CTX, ALL).isName === false);

  const B = I.RULES.BLUES;
  ok('B5 BLUES: you get the group first, and the person is gated by standing',
    I.meeting(B, CTX, { asked: true }).shown === B.faction &&
    !I.meeting(B, CTX, { asked: true }).isName &&
    I.meeting(B, CTX, { asked: true, standing: true }).shown === CTX.full);

  const R = I.RULES.REMNANTS;
  ok('B6 REMNANTS: a surname on the first ask, the first name only from somebody else',
    I.meeting(R, CTX, { asked: true }).shown === 'HOLLAND' &&
    !I.meeting(R, CTX, { asked: true }).isName &&
    I.meeting(R, CTX, { asked: true, overheard: true }).shown === CTX.full);

  const CH = I.RULES.CHURCH;
  ok('B7 CHURCH: they move first, and being named carries the not-forgetting',
    I.meeting(CH, CTX, {}).asks === 'YOUR NAME' &&
    I.meeting(CH, CTX, { asked: true }).isName === true &&
    I.meeting(CH, CTX, { asked: true }).remembers === true);

  const H = I.RULES.HOMELESS;
  ok('B8 HOMELESS: the name is not the transaction - honesty is, and it is pressable',
    I.meeting(H, CTX, {}).asks === 'WHERE YOU SLEEP' &&
    !I.meeting(H, CTX, { asked: true }).isName &&
    I.meeting(H, CTX, { honest: true }).isName === true &&
    !!I.answerFor(H, CTX, {}));

  ok('B9 HOMELESS: the price is charged for lying, never for asking',
    I.askOutcome(H, CTX, {}).cost === '' && I.RULES.HOMELESS.costOn === 'lie');

  const AM = I.RULES.AMALGAMATION;
  ok('B10 AMALGAMATION: nothing on screen explains it (canon, verbatim)',
    AM.explain === false && I.meeting(AM, CTX, {}).why === '' &&
    I.meeting(AM, CTX, {}).explain === false &&
    I.meeting(AM, CTX, {}).used === true);

  const AN = I.RULES.ANARCHISTS;
  ok('B11 ANARCHISTS: the chosen name arrives unasked and the birth name never',
    I.meeting(AN, CTX, {}).shown === 'RUBEN' &&
    I.meeting(AN, CTX, ALL).shown === 'RUBEN' &&
    /INSULT/.test(I.askOutcome(AN, CTX, {}).cost));

  /* A BUTTON THAT DOES NOTHING IS A LIE. Every button the organ offers must
     either move the state or be a mistake his canon deliberately allows. */
  let liars = [];
  keys.forEach(k => {
    const r = I.RULES[k];
    [{}, { asked: true }, ALL].forEach(st => {
      const label = I.buttonFor(r, CTX, st);
      if (!label) return;
      const o = I.askOutcome(r, CTX, st);
      if (!o.moved && !o.cost) liars.push(k + ' @' + JSON.stringify(st));
    });
  });
  ok('B12 no rule offers a button that neither moves anything nor costs anything',
    liars.length === 0, liars.join('; '));

  /* NO RULE HANDS BACK MORE THAN IT IS ALLOWED TO. The four "never" rules must
     never produce the person's name under ANY combination of earning state. */
  const nevers = keys.filter(k => I.RULES[k].earn === 'never');
  let leaked = nevers.filter(k => I.meeting(I.RULES[k], CTX, ALL).shown === CTX.full);
  ok('B13 no earn:never faction ever leaks the full name, under any state',
    leaked.length === 0 && nevers.length === 4, 'leaked: ' + leaked.join(', '));

  /* THE ~85% WHO RUN WITH NOBODY. This is Paolo 7/31, already shipped, already
     his favourite bit. A faction layer that changes it is a regression. */
  ok('B14 DEFAULT is byte-for-byte the old ruling: no name until you ask, then the name',
    I.meeting(I.DEFAULT, CTX, {}).shown === null &&
    I.meeting(I.DEFAULT, CTX, { asked: true }).shown === CTX.full &&
    I.buttonFor(I.DEFAULT, CTX, {}) === 'Ask their name');
  ok('B15 an unknown or absent faction resolves to DEFAULT, never to a guess',
    I.ruleOf(null) === I.DEFAULT && I.ruleOf('NOT_A_FACTION') === I.DEFAULT &&
    I.ruleOf('') === I.DEFAULT);
  ok('B16 all three faction vocabularies resolve: graph id, dress key, quest @ROLE token',
    I.ruleOf('Trades') === I.RULES.TRADES && I.ruleOf('TRADES') === I.RULES.TRADES &&
    I.ruleOf('Social Forces') === I.RULES.SOCIAL_FORCES &&
    I.ruleOf('Triads') === I.RULES.SOCIAL_FORCES);
}

/* ------------------------------------------------- C. THE REAL RUN, TAPPED */
async function partC() {
  console.log('C. IT REACHES THE PLAYER (the built run, in a real browser)');

  const built = fs.readFileSync(RUN_FILE, 'utf8');
  ok('C0 the organ is inlined in the file the alpha actually loads',
    built.includes('bohemia_introductions.js') && built.includes('BohemiaIntros'));

  const src = fs.readFileSync(RUN_SRC, 'utf8');
  ok('C1 the run\'s NAME row is rewritten from the organ, not printed beside it',
    /applyIntroToCard\(\s*BohemiaPeople\.cardFor\(/.test(src),
    'the card would show people.js\'s name next to the organ\'s handle');
  ok('C2 the one button\'s label comes from the organ, not a hardcoded string',
    /BohemiaIntros\.buttonFor\(/.test(src) &&
    !/ask\.textContent\s*=\s*'Ask their name'/.test(src));

  const { chromium } = requirePlaywright();
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [];
  page.on('pageerror', e => errors.push('PAGEERROR: ' + e.message));
  try {
    await page.goto('file://' + RUN_FILE);
    await page.waitForFunction(() => window.__RUN_READY === true, null, { timeout: 90000 });
    await page.evaluate(() => window.__RUN.wipeSaves());

    /* THE ORGAN IS LIVE IN THE PAGE, and it is the same one on disk. */
    const live = await page.evaluate(() => typeof BohemiaIntros !== 'undefined'
      ? { n: BohemiaIntros.keys().length, def: BohemiaIntros.DEFAULT.key } : null);
    ok('C3 the organ is loaded and complete inside the running game',
      !!live && live.n === 16 && live.def === 'NOBODY', JSON.stringify(live));

    /* EVERY BODY ON THE BLOCK RESOLVES AN INTRODUCTION. This is the claim a
       name-grep cannot make: the run's own reporting hook is asked what each
       person's card would say, so a wiring that exists but never runs fails. */
    const people = await page.evaluate(() => window.__RUN.people());
    ok('C4 the block has people to meet', !!people && people.people.length > 0,
      people ? String(people.n) : 'no people');
    const withIntro = (people.people || []).filter(p => p.intro);
    ok('C5 every person on the block resolves an introduction through the organ',
      withIntro.length === people.people.length,
      withIntro.length + '/' + people.people.length);

    /* THE DEFAULT PATH, ON THE REAL SURFACE. An ambient neighbour with no faction
       must behave exactly like 7/31: no name, one button, then the name. */
    const plain = withIntro.filter(p => p.intro.rule === 'NOBODY')[0];
    ok('C6 an unaffiliated neighbour still starts with no name and one ask button',
      !!plain && plain.intro.shown === null && plain.intro.button === 'Ask their name',
      plain ? JSON.stringify(plain.intro) : 'no unaffiliated person on the block');

    /* DRIVE IT THROUGH THE REAL DOM. Open the real card, press the real button,
       read the real row. A side door into the same function is what this lane
       shipped a broken allegiance line behind on 8/11. */
    const opened = await page.evaluate(() => {
      const a = (SIM && SIM.agents || []).filter(x => x.loc && x.loc.mode === 'out')[0]
             || (SIM && SIM.agents || [])[0];
      if (!a) return null;
      openPerson(a);
      const rows = [...document.querySelectorAll('#idcard .r')]
        .map(r => [r.querySelector('.k').textContent, r.querySelector('.v').textContent]);
      const btn = document.getElementById('pplask');
      return { rows, btn: btn ? btn.textContent : null, id: a.id };
    });
    ok('C7 the real card opens with a real NAME row and a real button',
      !!opened && opened.rows.some(r => r[0] === 'NAME' || r[0] === 'KNOWN AS'),
      JSON.stringify(opened && opened.rows));

    const beforeName = (opened.rows.find(r => r[0] === 'NAME' || r[0] === 'KNOWN AS') || [])[1];
    const after = await page.evaluate(() => {
      const b = document.getElementById('pplask');
      if (b) b.click();
      return [...document.querySelectorAll('#idcard .r')]
        .map(r => [r.querySelector('.k').textContent, r.querySelector('.v').textContent]);
    });
    const afterRow = after.find(r => r[0] === 'NAME' || r[0] === 'KNOWN AS');
    ok('C8 pressing the real button changes what the real card says they are called',
      !!afterRow && afterRow[1] !== beforeName,
      'before ' + JSON.stringify(beforeName) + ' after ' + JSON.stringify(afterRow));

    /* THE CONTRADICTION TEST. Force a faction whose handle is NOT a name and
       assert the card shows the handle and NOT the full name people.js would
       hand over. This is failure mode 3, driven on the surface he plays. */
    const forced = await page.evaluate(() => {
      const a = (SIM && SIM.agents || [])[0];
      const orig = window.factionForPerson;
      window.factionForPerson = function () { return 'TRADES'; };
      openPerson(a);
      /* ASK, then read. The first version of this claim opened a DIFFERENT agent
         from the one C7/C8 had asked and then asserted the card showed a trade --
         it showed YOU HAVE NOT ASKED, correctly, and the probe was the thing that
         was wrong. Fix the ruler, never the target (Paolo 8/1). */
      const ask = document.getElementById('pplask');
      if (ask) ask.click();
      const rows = [...document.querySelectorAll('#idcard .r')]
        .map(r => [r.querySelector('.k').textContent, r.querySelector('.v').textContent]);
      const who = personFor(a);
      const real = BohemiaPeople.generatedName(who.key);
      const hint = rows.find(r => r[0] === 'HOW YOU GET THE REST');
      window.factionForPerson = orig;
      return { rows, real, hint: hint ? hint[1] : null,
               head: document.getElementById('spk') ? document.getElementById('spk').textContent : null };
    });
    const shownRow = forced.rows.find(r => r[0] === 'KNOWN AS' || r[0] === 'NAME');
    ok('C9 a Trades member you asked reads as their TRADE, never as their name',
      !!shownRow && shownRow[0] === 'KNOWN AS' && shownRow[1] !== forced.real,
      JSON.stringify(shownRow) + ' real name would be ' + forced.real);
    ok('C10 the card tells the player how to get the rest, in his canon\'s own terms',
      forced.hint === 'HIRE THEM TWICE', JSON.stringify(forced.hint));
    ok('C11 no row anywhere on that card leaks the name they have not earned',
      forced.rows.every(r => !String(r[1]).includes(forced.real)),
      JSON.stringify(forced.rows));

    /* THE ONE UNBUILT CONDITION WHOSE SYSTEM ALREADY EXISTS. The Blues gate the
       name on REPUTATION, and the real FactionWorld already carries the player's
       standing. Move it and the card must change by itself -- if it does not, the
       binding is decoration and the mechanic never completes in play. */
    const blues = await page.evaluate(() => {
      const a = (SIM && SIM.agents || [])[0];
      const orig = window.factionForPerson;
      window.factionForPerson = function () { return 'Blues'; };
      const read = () => {
        openPerson(a);
        const b = document.getElementById('pplask'); if (b) b.click();
        const rows = [...document.querySelectorAll('#idcard .r')]
          .map(r => [r.querySelector('.k').textContent, r.querySelector('.v').textContent]);
        return (rows.find(r => r[0] === 'KNOWN AS' || r[0] === 'NAME') || [])[1];
      };
      const before = read();
      /* the same call the world bridge makes when a quest resolves */
      CTX.factions.shiftStanding('Blues', 'player', 20, false);
      const after = read();
      const real = BohemiaPeople.generatedName(personFor(a).key);
      window.factionForPerson = orig;
      return { before, after, real };
    });
    ok('C13 a Blues member is the GROUP until the group has an opinion about you',
      blues.before === 'THE BLUES' && blues.before !== blues.real,
      JSON.stringify(blues));
    ok('C14 moving real faction standing turns that group into a person, by itself',
      blues.after === blues.real && blues.after !== blues.before,
      JSON.stringify(blues));

    /* THE OTHER BUTTON. The Homeless asked YOU something, and answering it
       honestly is the unlock. If that move is not pressable on the real surface
       the mechanic is decoration and the card is a description of a game. */
    const homeless = await page.evaluate(() => {
      const a = (SIM && SIM.agents || [])[0];
      const orig = window.factionForPerson;
      window.factionForPerson = function () { return 'HOMELESS'; };
      openPerson(a);
      const rows = () => [...document.querySelectorAll('#idcard .r')]
        .map(r => [r.querySelector('.k').textContent, r.querySelector('.v').textContent]);
      const asked = (rows().find(r => r[0] === 'THEY ASKED YOU') || [])[1];
      const btn = document.getElementById('pplanswer');
      const label = btn ? btn.textContent : null;
      if (btn) btn.click();
      const after = (rows().find(r => r[0] === 'NAME' || r[0] === 'KNOWN AS') || [])[1];
      const real = BohemiaPeople.generatedName(personFor(a).key);
      window.factionForPerson = orig;
      return { asked, label, after, real };
    });
    ok('C15 the Homeless ask YOU where you sleep, and the answer is a real button',
      homeless.asked === 'WHERE YOU SLEEP' && !!homeless.label,
      JSON.stringify(homeless));
    ok('C16 answering honestly is what earns their name, on the real surface',
      homeless.after === homeless.real, JSON.stringify(homeless));

    ok('C12 the run threw no errors while doing any of that',
      errors.length === 0, errors.slice(0, 3).join(' | '));
  } finally { await browser.close(); }
}

/* ------------------------------------------------------ D. NOTHING INVENTED */
function partD() {
  console.log('D. MECHANISM MINE, CONTENTS HIS');

  const js = fs.readFileSync(ORGAN, 'utf8');
  /* strip the header comment: a gate that cannot tell a mention from a use is
     the broken one (Paolo 8/1, and this lane has made that exact mistake). */
  const code = js.split('\n').filter(l => !/^\s*(\/\/|\*|\/\*)/.test(l)).join('\n');

  ok('D1 the organ has no dialogue table of its own',
    !/\bLINES\s*[:=]/.test(code) && !/\bSAYS\s*[:=]/.test(code));
  ok('D2 the organ has no name pool of its own - names come from people.js',
    !/\bGIVEN\s*[:=]/.test(code) && !/\bSURNAME\s*[:=]/.test(code) &&
    !/\bNAMES\s*[:=]\s*\[/.test(code));

  /* every string the organ can return must be third-person mechanical narration,
     never a character speaking. A quoted line is the tell. */
  const rules = Object.keys(I.RULES).map(k => I.RULES[k]);
  const returned = [];
  rules.concat([I.DEFAULT]).forEach(r => {
    [r.next, r.mech, r.asks, r.blocked].forEach(s => { if (s) returned.push(s); });
    [{}, { asked: true }, ALL].forEach(st => {
      const m = I.meeting(r, CTX, st);
      [m.next, m.why, m.asks, m.blocked, m.cost].forEach(s => { if (s) returned.push(s); });
    });
  });
  Object.keys(I.COSTS).forEach(k => { if (I.COSTS[k]) returned.push(I.COSTS[k]); });
  const quoted = returned.filter(s => /^["'“]/.test(s.trim()) || /\bI\b|\byou're\b/i.test(s) === null);
  ok('D3 nothing the organ returns is a quoted line of speech',
    quoted.length === 0, quoted.slice(0, 3).join(' | '));

  /* the labels. Every one must be a slice of something the caller passed in, or
     the faction's own name. If a label ever appears that is in none of those, a
     word got invented. */
  const sources = [CTX.full, 'RUBEN', 'HOLLAND', CTX.trade, CTX.work]
    .concat(rules.map(r => r.faction));
  const bad = [];
  rules.forEach(r => {
    [{}, { asked: true }, ALL].forEach(st => {
      const s = I.meeting(r, CTX, st).shown;
      if (s && !sources.some(src => src && s.includes(src))) bad.push(r.key + ': ' + s);
    });
  });
  ok('D4 every label the organ shows is derived from what the engine handed it',
    bad.length === 0, bad.join('; '));

  /* THE PAGE HE LOOKS AT runs the real module, not a retelling of it. */
  const page = fs.readFileSync(PAGE, 'utf8');
  ok('D5 the judge page runs the REAL organ, inlined, not a reimplementation',
    page.includes('function askOutcome(rule, ctx, st)') &&
    page.includes('BohemiaIntros.meeting('));
  ok('D6 the judge page quotes his canon paragraph on every card',
    Object.keys(I.RULES).every(k => page.includes(I.RULES[k].canon.slice(0, 60))));
  /* NO QUEUE. Paolo 8/9, EVERYTHING IS A THUMB: a numbered queue of pending
     verdicts is banned, and this page is a LOOK, not a judgement. The first
     version of this claim grepped for the WORD "verdict" and failed on the
     page's own sentence "Nothing here needs a verdict" -- a checker that cannot
     tell a use from a mention is the broken one (Paolo 8/1). So it checks for the
     MACHINERY instead: thumb controls, a vote store, an export button. */
  const machinery = [/id=["']export/i, /downloadverdict|exportverdict/i,
                     /class=["'][^"']*thumb/i, /data-(vote|verdict|thumb)=/i,
                     /VERDICTS\s*=\s*\{/];
  const found = machinery.filter(re => re.test(page)).map(String);
  ok('D7 the judge page asks him for nothing - no thumb controls, no verdict export',
    found.length === 0, found.join(' | '));
}

